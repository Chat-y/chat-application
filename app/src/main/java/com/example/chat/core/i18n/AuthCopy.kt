@Composable
fun rememberAuthCopy(): (String) -> String {
    val context = LocalContext.current
    AuthI18n.install(context)
    return remember(context, context.resources.configuration.locales.toLanguageTags()) {
        val ids = authResourceNames.mapValues { (_, name) -> context.resources.getIdentifier(name, "string", context.packageName) };
        { english: String -> ids[english]?.takeIf { it != 0 }?.let(context::getString) ?: english }
    }
}

/** Positional resource placeholders keep dynamic identifiers out of translatable sentence order. */
@Composable
fun authFormatted(key:String,vararg arguments:Any):String {
    val copy=rememberAuthCopy()
    val locale=LocalContext.current.resources.configuration.locales[0]
    return String.format(locale,copy(key),*arguments)
}

/** Capture localized formatting once so event handlers can format resource templates too. */
@Composable
fun rememberAuthFormat(): (String,Any) -> String {
    val copy=rememberAuthCopy()
    val locale=LocalContext.current.resources.configuration.locales[0]
    return remember(copy,locale) { {key,value->String.format(locale,copy(key),value)} }
}
